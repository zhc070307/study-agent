    await page.getByRole('button',{name:'打开 example.html',exact:true}).click();
    assert.match(await page.locator('.file-text').innerText(),/<script>/);
    await page.getByRole('button',{name:'关闭 example.html',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('#document-title').textContent.includes('example.html'));
    assert.equal(await page.getByRole('button',{name:'关闭 example.html',exact:true}).count(),0);
    await page.getByRole('button',{name:'桌面',exact:true}).click();
    const unsafeMarkdown='# 查看内容\n\n<img src="https://example.com/should-not-load.png" onerror="window.unsafe=1"><script>window.unsafe=1</script>';
    await page.locator('#file-input').setInputFiles({name:'untrusted.md',mimeType:'',buffer:Buffer.from(unsafeMarkdown)});
    await page.getByRole('button',{name:'打开 untrusted.md',exact:true}).click();
    assert.equal(await page.locator('.markdown-body h1').innerText(),'查看内容');
    assert.equal(await page.locator('.markdown-body img').count(),0);
    assert.equal(await page.evaluate(()=>window.unsafe),undefined);
    await page.getByRole('button',{name:'源码',exact:true}).click();
    assert.equal(await page.locator('.file-text').textContent(),unsafeMarkdown);
    const mobile=await browser.newPage({viewport:{width:390,height:844}});
    mobile.on('pageerror',error=>errors.push(error.message));await mobile.goto(origin);
    assert.ok(!(await mobile.locator('.assistant').isVisible()));
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.getByRole('button',{name:'打开助理',exact:true}).last().click();
    assert.ok(await mobile.getByLabel('向助理提问').isVisible());
    assert.deepEqual(errors,[]);
    assert.ok(requests.filter(url=>/^https?:/.test(url)).every(url=>url.startsWith(origin+'/')), '不得向外部服务发送请求');
    console.log('GUI 检查通过：文件夹与任务清单、Markdown 预览/源码、LaTeX 源码、PDF 真实划词提问与页码、标签/并排/恢复、窄屏和无外部请求。');

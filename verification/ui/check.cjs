    assert.equal(await page.locator('.file-card').count(),2);
    await page.getByLabel('选择 导数笔记.md',{exact:true}).check();
    await page.getByRole('button',{name:'整理文件',exact:true}).click();
    await page.locator('#organize-name').fill('这次的材料'); await page.locator('#picker-confirm').click();
    await page.waitForFunction(()=>document.querySelector('#conversation').textContent.includes('已在本页'));
    await page.getByRole('button',{name:'文件夹',exact:true}).click();
    await page.getByRole('button',{name:'这次的材料',exact:true}).click();
    assert.equal(await page.locator('.file-card').count(),1);
    await page.getByRole('button',{name:'组织练习',exact:true}).click();
    assert.match(await page.locator('#conversation').innerText(),/并非根据关联文件生成/);
    await page.getByLabel('向助理提问').fill('桌面的草稿');
    await page.getByRole('button',{name:'打开 导数笔记.md',exact:true}).click();
    await page.waitForSelector('.markdown-body');
    await page.getByRole('button',{name:'源码',exact:true}).click();
    assert.equal(await page.locator('.file-text').textContent(),fs.readFileSync(path.join(root,'ui/samples/notes/derivatives.md'),'utf8'));
    await page.getByRole('button',{name:'预览',exact:true}).click();
    await page.locator('.markdown-body p').first().dblclick();
    await page.getByRole('button',{name:'问助理',exact:true}).click();
    await page.getByLabel('向助理提问').fill('这里的平均变化率是什么？');
    await page.getByRole('button',{name:'发送',exact:true}).click();
    assert.match(await page.locator('#conversation').innerText(),/文字选区/);
    await page.getByLabel('向助理提问').fill('文件里的草稿');
    await page.getByRole('button',{name:'并排查看',exact:true}).click();
    await page.locator('#picker-body input[value="answer"]').check(); await page.locator('#picker-confirm').click();
    await page.waitForFunction(()=>document.querySelectorAll('.document-pane').length===2);
    assert.match(await page.locator('.document-pane').last().innerText(),/解题思路/);
    await page.getByRole('button',{name:'关闭并排文件',exact:true}).click();
    const savedScroll=await page.locator('.workspace').evaluate(element=>{element.scrollTop=180;return element.scrollTop;});
    assert.ok(savedScroll>0);
    await page.getByRole('button',{name:'桌面',exact:true}).click();
    assert.equal(await page.getByLabel('向助理提问').inputValue(),'桌面的草稿');
    await page.getByRole('button',{name:'打开 导数笔记.md',exact:true}).click();
    assert.equal(await page.getByLabel('向助理提问').inputValue(),'文件里的草稿');
    assert.equal(await page.locator('.workspace').evaluate(element=>element.scrollTop),savedScroll);
    await page.getByRole('button',{name:'桌面',exact:true}).click();
    await page.getByRole('button',{name:'文件夹',exact:true}).click();
    await page.getByRole('button',{name:'课程材料',exact:true}).click();
    await page.getByRole('button',{name:'打开 导数与微分.pdf',exact:true}).click();
    await page.waitForSelector('.pdf-sheet[data-rendered="true"]');
    const pdfText=page.locator('.textLayer span').filter({hasText:'导数与微分'}).first();
    await pdfText.dblclick();

const root = path.resolve(__dirname, '../..');
const store = path.join(root, 'vendor/deepseek-harness/node_modules/.pnpm');
const packageName = fs.existsSync(store) && fs.readdirSync(store).find(name => /^playwright@\d/.test(name));
const playwrightModule = process.env.STUDY_UI_PLAYWRIGHT_MODULE || (packageName && path.join(store, packageName, 'node_modules/playwright'));
